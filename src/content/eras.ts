export function eraName(iso3: string, year: number, currentName: string): string {
  for (const [from, to, name, parent] of ERAS[iso3] ?? []) {
    if (year >= from && year <= to) {
      const base = name ?? currentName;
      return parent ? `${base}, ${parent}` : base;
    }
  }
  return currentName;
}
